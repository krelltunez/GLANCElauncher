#!/usr/bin/env node
// Writes app/src/main/assets/lucide-aliases.txt: the icons lucide exports under more than one
// name, one icon per line. lastGLANCE ships one drawable per icon, under whichever spelling won
// when its drawables were generated, while a chore stores whichever spelling its picker offered
// (LucideIcons.candidates). Rerun when lastGLANCE moves its lucide-react pin:
//
//   node tools/gen-lucide-aliases.mjs ../lastGLANCE
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const app = resolve(process.argv[2] ?? '../lastGLANCE')
const require = createRequire(join(app, 'package.json'))
const Lucide = require('lucide-react')
const { version } = require('lucide-react/package.json')

// The same filter as lastGLANCE's src/icons/registry.ts.
const spellings = new Map()
for (const [name, value] of Object.entries(Lucide)) {
  if (name.endsWith('Icon') || name === 'createLucideIcon') continue
  if (value === null || typeof value !== 'object' || !('$$typeof' in value)) continue
  if (!spellings.has(value)) spellings.set(value, new Set())
  spellings.get(value).add(name.replace(/^Lucide/, ''))
}

const lines = [...spellings.values()]
  .filter(names => names.size > 1)
  .map(names => [...names].sort().join(' '))
  .sort()

const out = join(dirname(fileURLToPath(import.meta.url)), '../app/src/main/assets/lucide-aliases.txt')
writeFileSync(out, `# lucide-react ${version}. Generated by tools/gen-lucide-aliases.mjs.\n${lines.join('\n')}\n`)
console.log(`${lines.length} icons with aliases, lucide-react ${version}`)
